package dbms.parser;

/** Виды кусочков (токенов), на которые делится запрос. */
public enum TokenType {

    /** Слово: команда или имя таблицы, столбца, индекса. */
    IDENT,

    /** Число. */
    NUMBER,

    /** Текст в одинарных кавычках (даты тоже пишутся так). */
    STRING,

    /** Знак: скобка, запятая, точка с запятой, звёздочка, сравнение. */
    SYMBOL,

    /** Конец запроса. */
    EOF
}
